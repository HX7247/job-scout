"""Review a CV and cover letter against one specific job. Never invents a claim.

WHERE THIS DOES NOT GO - read before adding a data source
-----------------------------------------------------------
The obvious way to make a CV review feel authoritative is to say "recruiters at this
company look for X" or "other applicants typically Y". Neither claim would be true here,
because there is no legitimate source for either: Glassdoor's API closed to developers
in 2022 (see enrich.py's module docstring - this app already made that call once), and
no one publishes what "other applicants" wrote, nor should they. Inventing either would
be a fabricated statistic dressed up as insight, and the one thing worse than no feedback
is confident, wrong feedback.

What this module uses instead, all of it real:
  * the job's own posted text - title, full description, whatever it actually asks for
  * the candidate's own CV/profile skills, via cv.extract_skills - same matcher the rest
    of the app already uses for scoring, so a skill counted here is a skill counted there
  * the employer's own stated values, via interview.company_values - already fetched
    honestly elsewhere in this app; reused here, not refetched
  * real, verified-today CV and cover-letter guidance from actual career-advice sites
    (RESOURCES below) - each one checked with a live request before being hardcoded, the
    same discipline tools/discover_assessments.py uses for its interview-prep links

THE FACT-CHECKING PASS
-----------------------
Looking at how established open-source resume-review tools handle this (a project called
resume-helper on GitHub runs an adversarial Writer/Fact-Checker split, where the
Fact-Checker "compares resume claims against the original input to catch any invented
details" before anything reaches the user), the design here does the same thing natively
rather than as a second expensive model call: every piece of Claude-generated feedback
must cite the exact word or phrase it is grounded in, and _verify_evidence() checks that
citation against the actual source text before the suggestion is allowed through. A
suggestion whose evidence cannot be found gets dropped, not shown with a caveat - a
feedback tool that could ever tell someone "you claimed X" when they did not is worse
than a feedback tool with fewer things to say. This mirrors interview.py's _evidence_map,
which does the equivalent job for interview prep: every piece of advice tied to a
specific, checkable fact, never a vibe.

WHAT NEVER GETS STORED
-----------------------
The CV is read fresh from disk for the length of one request and never kept - CVProfile
has no field for it, on the same principle documented in cv.py. A cover letter, whether
generated by apply.py or pasted in by the user, is used in memory and returned in the
response; nothing here writes either one to the database, to profile.json, or to a log
line.
"""
